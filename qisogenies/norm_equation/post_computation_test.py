from qarton.circuit import QartonBool, UInt
from qarton.signed_arithmetic import SInt
from qarton.tests import run_real

from .post_computation import PostComp
from .ring_integers import RingInteger
from .util import InstanceData


@run_real(PostComp)
def test_PostComp() -> None:

    d = InstanceData(
        w=512,
        x=22,
        e=497,
        p=88381546413195830490356121814345177109849335243162749316048866938595612502926212981848292492799412243073940471444121917248865926738905612439870244913151,
        nb_primes=20,
    )
    delta_1 = RingInteger(
        d.p,
        d.w // 2 + d.w // 4 + 10,
        -664934399085904671530736344392541485641882045852077914710074031340256750934267613421280028408048583588988869137,
        1,
    )
    delta_2 = RingInteger(
        d.p,
        d.w // 2 + d.w // 4 + 10,
        -6873836650501516337356643301363937580159737576602221543059408649595403053601702296463008876543535557584490642625,
        1009985354532144140565081993407277265,
    )
    z = UInt(
        373848239657816976707926151944642294087276159332143702521991912264646683893
    )
    which_case_when_2mod8 = QartonBool(0)
    D1 = SInt(
        5186019115995769278029234923099808360509992683233869899561317011399005243794609999922485422243664043719471143170284995328017377440885244672402049829,
        512,
    )
    D2 = SInt(
        761991246198338554250794010546965138993632356752283417113283981566624998, 512
    )
    b1 = UInt(17780002345000554104588324206128082857)
    b2 = UInt(7597351924821685770870407348159349962)
    N = UInt(
        881340839743179651256924629676994118826089293512667182798235188874420186160
    )

    inputs = (delta_1, delta_2, z, which_case_when_2mod8, D1, D2, b1, b2, N)

    qc = PostComp(d)
    print(qc.nbr_qubits())
    assert qc.validate_input(inputs)
    assert qc.simulate(inputs) == qc.dummy_classical_function(inputs)
