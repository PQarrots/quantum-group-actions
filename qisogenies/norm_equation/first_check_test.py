def test_FixCoeff() -> None:

    d = InstanceData(
        w=512,
        x=22,
        e=497,
        p=88381546413195830490356121814345177109849335243162749316048866938595612502926212981848292492799412243073940471444121917248865926738905612439870244913151,
        nb_primes=20,
    )

    delta_1 = RingInteger(
        d.p,
        394,
        -1794781731805524209334948793193412764079270903383208215925826974659835499350811918474009101588684129515106078525,
        1,
    )
    delta_2 = RingInteger(
        d.p,
        394,
        -5897704392278387740459739308402121365642848765851215840408122510220063127310863677046623113966702385970538204222237,
        2025075031620188808068788088795367945,
    )
    N = 3543202555509463517522426978092429208775398208346546626359066163738671776764
    z = 2770493337404233620592843930897897014876629861571605613538716625639137620334729

    conds = BitVector(1, 1)
    which_case_when_2mod8 = QartonBool(0)
    D1 = SInt(
        2987436348055032834536421847885489836130332060865294560943782033421458034776370278209926616210517418682974242667102214417435683976693933049901323504015,
        512,
    )
    D2 = SInt(
        1025786027004264397647279711000698797185919350026802472442023093724575742, 512
    )
    qc = FixCoefft(d)

    # delta_1, delta_2, N and z are preserved (input_output) registers, so they
    # come back unchanged, alongside the newly computed conds, D1, D2 and
    # which_case_when_2mod8.
    assert qc.simulate((delta_1, delta_2, N, z)) == (
        delta_1,
        delta_2,
        N,
        z,
        conds,
        D1,
        D2,
        which_case_when_2mod8,
    )


@run_real(FirstCheck)
def test_FirstCheck() -> None:

    d = InstanceData(
        w=512,
        x=22,
        e=497,
        p=88381546413195830490356121814345177109849335243162749316048866938595612502926212981848292492799412243073940471444121917248865926738905612439870244913151,
        nb_primes=20,
    )

    N = UInt(
        3543202555509463517522426978092429208775398208346546626359066163738671776764
    )
    alpha = RingInteger(
        d.p,
        256,
        3362604632995698792291004339970379322021014661751296003886280466636367226039,
        1,
    )
    algo_input = (N, alpha)
    precomp_result = (
        UInt(2025075031620188808068788088795842332),
        UInt(
            21665096646157155732551585610707783191634592205505528279090171780537778733
        ),
        UInt(
            42459568305255091840276783417359507940387538545898246828283392399770150625
        ),
        UInt(
            9427204907945286468908359558814588312948437989861559987276078374015016740382
        ),
    )
    rchoice = UInt(618261)

    delta_1 = RingInteger(
        d.p,
        394,
        -6096898993294054807895110883011244370799016842613900690724618883279050919735780225274914207878705994945837390869,
        1,
    )
    delta_2 = RingInteger(
        d.p,
        394,
        -19222977599264523481394928066129853778196369133423523003214930208274635418388102496403436616738010062613808736299,
        2025075031620188808068788088795224071,
    )
    D1 = SInt(
        33077576270888137633266723268915705641659529226867508908608946997716234904003401042087626466488705443066792331231703097107600265267707748341589078595,
        512,
    )
    D2 = SInt(
        3484609679576948105703416504646495204826498563877645065828675185385861350, 512
    )
    z = UInt(75868848047767843586476268694579215726649902156622546967554041417228783813)
    bvv = BitVector(1, 1, 1, 1, 1, 1)
    which_case_when_2mod8 = QartonBool(0)

    qc = FirstCheck(d)
    assert qc.simulate((algo_input, precomp_result, rchoice)) == (
        algo_input,
        precomp_result,
        rchoice,
        delta_1,
        delta_2,
        D1,
        D2,
        z,
        bvv,
        which_case_when_2mod8,
    )


